const intro = document.getElementById("intro");
const slideView = document.getElementById("slideView");
const counter = document.getElementById("counter");
const progressFill = document.getElementById("progressFill");
const slideCard = document.getElementById("slideCard");
const slideKicker = document.getElementById("slideKicker");
const slideSymbol = document.getElementById("slideSymbol");
const slideTitle = document.getElementById("slideTitle");
const slideParagraph = document.getElementById("slideParagraph");
const prevButton = document.getElementById("prevButton");
const nextButton = document.getElementById("nextButton");
const hint = document.getElementById("hint");
let currentSlide = 0;

function showSlide(index) {
  currentSlide = Math.max(0, Math.min(index, slides.length - 1));
  const slide = slides[currentSlide];
  slideKicker.textContent = slide.kicker;
  slideSymbol.textContent = slide.symbol;
  slideTitle.textContent = slide.title;
  slideParagraph.textContent = slide.paragraph;
  counter.innerHTML = `${String(currentSlide + 1).padStart(2, "0")} <span>/</span> 18`;
  progressFill.style.width = `${((currentSlide + 1) / slides.length) * 100}%`;
  prevButton.style.visibility = currentSlide === 0 ? "hidden" : "visible";
  nextButton.innerHTML = currentSlide === slides.length - 1
    ? 'Start again <span>↻</span>'
    : 'Next <span>→</span>';
  hint.textContent = currentSlide === slides.length - 1 ? "thank you for reading, birthday girl ♡" : "one little page at a time ♡";
  slideCard.style.animation = "none";
  void slideCard.offsetWidth;
  slideCard.style.animation = "cardIn .35s ease both";
}

document.getElementById("startButton").addEventListener("click", () => {
  intro.classList.add("hidden");
  slideView.classList.remove("hidden");
  showSlide(0);
  window.scrollTo({ top: 0, behavior: "smooth" });
});

prevButton.addEventListener("click", () => {
  if (currentSlide > 0) showSlide(currentSlide - 1);
});

nextButton.addEventListener("click", () => {
  if (currentSlide < slides.length - 1) {
    showSlide(currentSlide + 1);
  } else {
    slideView.classList.add("hidden");
    intro.classList.remove("hidden");
    counter.innerHTML = '01 <span>/</span> 18';
    progressFill.style.width = "0%";
    window.scrollTo({ top: 0, behavior: "smooth" });
  }
});


